export const ALL_STAGES: StageConfig[] = Object.values(STAGES);
export const STAGE_LIST: StageConfig[] = ALL_STAGES.filter((s) => s.available);

export function getHomeStageForFighter(fighterId: FighterId): StageId {
  const owned = ALL_STAGES.find((s) => s.ownerFighterId === fighterId && s.available);
  if (owned) return owned.id;
  return ['kaede', 'rex', 'jin', 'zara', 'valentina'].includes(fighterId)
    ? 'bayside_harbor'
    : 'shibuya_dojo';
}

